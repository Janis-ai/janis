import { createDb } from '../../src/db/client.js';
import { pendingActions, agents, conversations, workspaces, users, workspaceMembers } from '../../src/db/schema.js';
import { eq } from 'drizzle-orm';
const db = await createDb();
const [a] = await db.select().from(pendingActions).where(eq(pendingActions.id, '940a2517-6d37-4ec5-87ba-143439f7d3e7'));
console.log('action.workspaceId:', a.workspaceId, '| conv:', a.conversationId, '| agent:', a.agentId);
const [ag] = await db.select({ id: agents.id, workspaceId: agents.workspaceId, hidden: agents.hidden, name: agents.name }).from(agents).where(eq(agents.id, a.agentId));
console.log('agent:', ag);
const [cv] = await db.select({ agentId: conversations.agentId, userProfile: conversations.userProfile }).from(conversations).where(eq(conversations.id, a.conversationId));
console.log('conv:', cv);
const ws = await db.select({ id: workspaces.id, name: workspaces.name }).from(workspaces);
console.log('workspaces:', ws);
const members = await db.select({ workspaceId: workspaceMembers.workspaceId, userId: workspaceMembers.userId, role: workspaceMembers.role }).from(workspaceMembers).where(eq(workspaceMembers.workspaceId, a.workspaceId));
console.log('members of action ws:', members);
const us = await db.select({ id: users.id, email: users.email }).from(users);
console.log('users:', us);
process.exit(0);
