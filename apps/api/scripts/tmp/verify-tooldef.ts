import { createDb } from '../../src/db/client.js';
import { agents } from '../../src/db/schema.js';
import { eq } from 'drizzle-orm';
const db = await createDb();
const [a] = await db.select({ config: agents.config }).from(agents).where(eq(agents.id, 'd408d7b5-fdad-49a4-a34d-11fa16e88135'));
const tools = (a?.config as { tools?: { name: string; bodyTemplate?: string }[] })?.tools ?? [];
const t = tools.find((x) => x.name === 'shopify_search_products');
const bt = t?.bodyTemplate ?? '';
console.log('has metafields:', bt.includes('metafields'));
console.log('has compareAt:', bt.includes('minVariantCompareAtPrice'));
console.log('has inventoryItem:', bt.includes('inventoryItem'));
console.log('variants window:', /variants\(first:(\d+)\)/.exec(bt)?.[1]);
process.exit(0);
