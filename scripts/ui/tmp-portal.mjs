import { chromium } from 'playwright';
import fs from 'node:fs';
const c = JSON.parse(fs.readFileSync('/tmp/slack-d.json','utf8'));
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 1400, height: 1400 } });
await ctx.addCookies([{ name:'d', value:c.d, domain:'.slack.com', path:'/', httpOnly:true, secure:true, sameSite:'Lax' }]);
await ctx.grantPermissions(['clipboard-read','clipboard-write'], { origin: 'https://app.slack.com' });
const page = await ctx.newPage();
await page.goto('https://app.slack.com/app-settings/T0PR0MCUX/A15NCEA7K/app-manifest', { waitUntil: 'domcontentloaded', timeout: 45000 });
await page.waitForTimeout(8000);
await page.locator('text=Copy to Clipboard').first().click();
await page.waitForTimeout(1000);
const manifest = JSON.parse(await page.evaluate(() => navigator.clipboard.readText()));
manifest.features.slash_commands = manifest.features.slash_commands.filter(x => x.command !== '/janis');
const updated = JSON.stringify(manifest, null, 4);
await page.locator('.cm-content, .CodeMirror').first().click();
await page.waitForTimeout(800);
await page.keyboard.press('ControlOrMeta+a');
await page.evaluate(async (txt) => { await navigator.clipboard.writeText(txt); }, updated);
await page.keyboard.press('ControlOrMeta+v');
await page.waitForTimeout(2000);
const save = page.getByRole('button', { name: /Save/i }).first();
await save.click();
await page.waitForTimeout(4000);
await page.locator('text=Copy to Clipboard').first().click();
await page.waitForTimeout(1000);
const now = JSON.parse(await page.evaluate(() => navigator.clipboard.readText()));
console.log('cmds:', now.features?.slash_commands?.length, 'janis present:', now.features?.slash_commands?.some(x=>x.command==='/janis'));
await browser.close();
