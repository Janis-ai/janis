import { launch, login } from './lib.mjs';
const { browser, page } = await launch();
await login(page);
await page.goto('http://localhost:5173/conversations', { waitUntil: 'domcontentloaded' });
await page.waitForSelector('.conv-row', { timeout: 15000 });
await page.locator('.conv-row').nth(2).click();
await page.waitForSelector('.conv-main', { timeout: 10000 });
const shot = (t) => page.screenshot({ path: `scripts/ui/out/seq-${t}.png`, clip: { x: 0, y: 0, width: 800, height: 100 } });
const infoPos = async () => page.evaluate(() => {
  const el = document.querySelector('.conv-mobile-head .cmh-info:not(.cmh-copilot)');
  if (!el || getComputedStyle(el).display === 'none') return null;
  const r = el.getBoundingClientRect();
  return { x: r.left + r.width / 2, y: r.top + r.height / 2 };
});
await page.setViewportSize({ width: 1400, height: 900 });
await page.waitForTimeout(400);
await page.setViewportSize({ width: 800, height: 900 });
await page.waitForTimeout(500);
let p = await infoPos();
await page.mouse.click(p.x, p.y);
await page.waitForTimeout(400);
await shot('open1');
console.log('click1 side:', await page.evaluate(() => getComputedStyle(document.querySelector('.conv-side')).display));
await page.setViewportSize({ width: 1400, height: 900 });
await page.waitForTimeout(500);
await page.setViewportSize({ width: 800, height: 900 });
await page.waitForTimeout(500);
p = await infoPos();
await page.mouse.click(p.x, p.y);
await page.waitForTimeout(400);
await shot('open2');
console.log('click2 side:', await page.evaluate(() => getComputedStyle(document.querySelector('.conv-side')).display));
await browser.close();
